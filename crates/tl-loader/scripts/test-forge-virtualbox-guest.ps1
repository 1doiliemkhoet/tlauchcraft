#requires -Version 5.1
<#
 VirtualBox Windows 10 guest preflight. NO Java, Forge, downloads or Minecraft paths.
 Writes evidence even on a failed check; never emits a PASS on partial checks.
 Must be launched from verified VirtualBox host harness or with -HostAttestation
 generated by that harness. Host state alone does not prove guest ACL safety.
#>
[CmdletBinding()]
param(
  [Parameter(Mandatory=$true)][string]$HostAttestation,
  [string]$EvidencePath='C:\ForgeAudit\virtualbox-preflight.json',
  [string]$StageParent='C:\ForgeAudit',
  [string]$JobSource='C:\ForgeAudit\ForgeJobProcess.cs'
)
Set-StrictMode -Version Latest
$ErrorActionPreference='Stop'
$checks = New-Object System.Collections.ArrayList
function Check([string]$name,[bool]$pass,[string]$detail) {
  [void]$checks.Add([ordered]@{name=$name;state=$(if($pass){'PASS'}else{'FAIL'});detail=$detail})
  if (-not $pass) { throw "CHECK_FAILED:$name : $detail" }
}
function Report([string]$status,[string]$errorText) {
  $body=[ordered]@{
    schema='tl-forge-vbox-preflight/v1'
    status=$status
    host_attestation=$HostAttestation
    guest_time_utc=[DateTime]::UtcNow.ToString('o')
    checks=@($checks.ToArray())
    error=$errorText
    java_executed=$false
    forge_execution_verified=$false
    instance_ready=$false
  }
  $json=$body|ConvertTo-Json -Depth 9
  $output=[IO.Path]::GetFullPath($EvidencePath)
  $parent=[IO.Path]::GetDirectoryName($output)
  if (-not [IO.Directory]::Exists($parent)) { [void][IO.Directory]::CreateDirectory($parent) }
  if ([IO.File]::Exists($output)) { throw "Evidence path already exists: $output" }
  [IO.File]::WriteAllText($output,$json,(New-Object Text.UTF8Encoding($false)))
  Write-Output $json
}
try {
  $hostEvidence = Get-Content -LiteralPath $HostAttestation -Raw | ConvertFrom-Json
  Check 'host_vm_configuration' ($hostEvidence.status -eq 'VBOX_HOST_CONFIG_PASS_NO_JAVA' -and $hostEvidence.vm -eq 'win10') 'Host evidence must prove all 8 adapters none, clipboard/dragdrop disabled, USB and VRDE off, zero configured shared folders'
  $root=[IO.Path]::GetFullPath($StageParent)
  $out=[IO.Path]::GetFullPath($EvidencePath)
  $bad = @($root -split '[\\/]' | Where-Object { $_ -match '^(?i:saves|worlds|profiles|instances|\.minecraft)$' })
  Check 'dedicated_guest_stage_parent' ($bad.Count -eq 0 -and $root -ne [IO.Path]::GetPathRoot($root) -and $out.StartsWith($root.TrimEnd([char[]]@('\','/'))+'\',[StringComparison]::OrdinalIgnoreCase)) 'Only new guest-local audit paths; no existing Minecraft paths'
  $net=@(Get-NetAdapter -ErrorAction Stop | Where-Object { $_.Status -eq 'Up' -and $_.InterfaceDescription -notmatch 'Loopback' })
  $routes=@(Get-NetRoute -AddressFamily IPv4 -DestinationPrefix '0.0.0.0/0' -ErrorAction Stop)
  $ip=@(Get-NetIPAddress -AddressFamily IPv4 -ErrorAction Stop | Where-Object { $_.IPAddress -notmatch '^127\.' -and $_.IPAddress -ne '0.0.0.0' })
  Check 'guest_no_active_network' ($net.Count -eq 0 -and $routes.Count -eq 0 -and $ip.Count -eq 0) "up_adapters=$($net.Count);default_routes=$($routes.Count);nonloopback_ipv4=$($ip.Count)"
  $mounts=@(Get-CimInstance Win32_LogicalDisk -ErrorAction Stop | Where-Object { $_.DriveType -eq 4 -or ($_.ProviderName -match 'VBOX|\\\\VBOXSVR') })
  $mapped=(& cmd.exe /d /c 'net use' 2>&1 | Out-String)
  $vboxControl=Join-Path $env:ProgramFiles 'Oracle\VirtualBox Guest Additions\VBoxControl.exe'
  Check 'guest_additions_shared_folder_inspection_available' (Test-Path -LiteralPath $vboxControl -PathType Leaf) 'VBoxControl.exe is needed to independently query guest shared folders'
  $sharedOutput=(& $vboxControl sharedfolder list 2>&1 | Out-String)
  $vboxExit=$LASTEXITCODE
  $reportedEmpty=($sharedOutput -match '(?im)No Shared Folders available|Shared Folder mappings \(0\):|0 shared folders|0 mappings')
  Check 'guest_no_host_shared_mounts' ($mounts.Count -eq 0 -and $mapped -notmatch '(?i)\\\\VBOXSVR|\\\\VBOXSRV' -and $vboxExit -eq 0 -and $reportedEmpty) "mapped_drive_count=$($mounts.Count);VBoxControl_exit=$vboxExit;no_share_report=$reportedEmpty"
  [void][IO.Directory]::CreateDirectory($root)
  $stage=Join-Path $root 'stage-forge-preflight'
  Check 'guest_fresh_stage' (-not (Test-Path -LiteralPath $stage)) 'stage must not preexist'
  $user=[Security.Principal.WindowsIdentity]::GetCurrent().User
  $security=New-Object Security.AccessControl.DirectorySecurity
  $security.SetAccessRuleProtection($true,$false)
  $rule=New-Object Security.AccessControl.FileSystemAccessRule($user,[Security.AccessControl.FileSystemRights]::FullControl,([Security.AccessControl.InheritanceFlags]'ContainerInherit,ObjectInherit'),[Security.AccessControl.PropagationFlags]::None,[Security.AccessControl.AccessControlType]::Allow)
  $security.AddAccessRule($rule)
  [void][IO.Directory]::CreateDirectory($stage)
  Set-Acl -LiteralPath $stage -AclObject $security -ErrorAction Stop
  $actual=Get-Acl -LiteralPath $stage
  $rules=@($actual.Access)
  $badWrite=@($rules | Where-Object { $_.AccessControlType -eq 'Allow' -and $_.IdentityReference.Value -match '(?i)Everyone|BUILTIN\\Users|Authenticated Users' -and (([int]$_.FileSystemRights -band [int][Security.AccessControl.FileSystemRights]::WriteData) -ne 0) })
  Check 'guest_stage_acl' ($actual.AreAccessRulesProtected -and $badWrite.Count -eq 0) "acl_protected=$($actual.AreAccessRulesProtected);world_writable_entries=$($badWrite.Count)"
  $probe=Join-Path $stage 'guest-only-write-probe.txt'
  [IO.File]::WriteAllText($probe,'stage-write-pass',(New-Object Text.UTF8Encoding($false)))
  Check 'guest_stage_write' (([IO.File]::ReadAllText($probe)) -eq 'stage-write-pass') 'Guest account may write only to new audited stage; unrelated filesystem restriction not inferred'
  Check 'job_helper_present' (Test-Path -LiteralPath $JobSource -PathType Leaf) 'Local approved JobObject helper is required'
  Add-Type -Path $JobSource -ErrorAction Stop
  $cmd=Join-Path $env:WINDIR 'System32\cmd.exe'
  $normal=[ForgeJobProcess]::Run($cmd,([string[]]@('/d','/c','exit','0')),$stage,10000)
  Check 'job_normal_exit' ($normal -eq 0) "exit=$normal"
  # Harmless Windows PowerShell grandchild without network access or Java.
  $powershell=Join-Path $env:WINDIR 'System32\WindowsPowerShell\v1.0\powershell.exe'
  $marker=Join-Path $stage 'child.pid'
  $grandchild=Join-Path $stage 'grandchild.ps1'
  $driver=Join-Path $stage 'driver.ps1'
  [IO.File]::WriteAllText($grandchild,'Start-Sleep -Seconds 60',(New-Object Text.UTF8Encoding($false)))
  $driverText=@'
param([string]$Grandchild,[string]$Marker)
$p=Start-Process -FilePath "$env:WINDIR\System32\WindowsPowerShell\v1.0\powershell.exe" -ArgumentList @('-NoProfile','-NonInteractive','-File',$Grandchild) -PassThru -WindowStyle Hidden
[IO.File]::WriteAllText($Marker,$p.Id.ToString())
Start-Sleep -Seconds 60
'@
  [IO.File]::WriteAllText($driver,$driverText,(New-Object Text.UTF8Encoding($false)))
  $timedOut=$false
  try { [void][ForgeJobProcess]::Run($powershell,([string[]]@('-NoProfile','-NonInteractive','-File',$driver,$grandchild,$marker)),$stage,5000) }
  catch [TimeoutException] { $timedOut=$true }
  Check 'job_timeout' $timedOut 'Native JobObject 5000ms timeout triggered'
  Check 'job_descendant_observed' (Test-Path -LiteralPath $marker -PathType Leaf) 'Grandchild PID marker written before timeout'
  $pidValue=[int][IO.File]::ReadAllText($marker)
  Start-Sleep -Milliseconds 500
  Check 'job_descendant_cleanup' ($null -eq (Get-Process -Id $pidValue -ErrorAction SilentlyContinue)) "grandchild_pid=$pidValue;not_running"
  Report 'VM_PREFLIGHT_PASS_NO_JAVA' $null
} catch {
  $failure=$_.Exception.Message
  try { Report 'VM_PREFLIGHT_FAILED_NO_JAVA' $failure } catch { Write-Error -ErrorAction Continue "Evidence write failed: $($_.Exception.Message)" }
  exit 2
}
